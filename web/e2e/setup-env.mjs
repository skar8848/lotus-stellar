// Writes web/.env.local (git-ignored) with the DEV signer enabled and the throwaway TESTNET keys
// from ../deployments/*.secrets.json (also git-ignored). Prints public keys only, never secrets.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Keypair } from "@stellar/stellar-sdk";

const here = path.dirname(fileURLToPath(import.meta.url));
const dep = path.resolve(here, "..", "..", "deployments");
const read = (f) => {
  try {
    return JSON.parse(fs.readFileSync(path.join(dep, f), "utf8"));
  } catch {
    return {};
  }
};
const secrets = { ...read("testnet.secrets.json"), ...read("testnet.classic.secrets.json") };
const want = { maker: "maker", taker: "taker", blocked: "blocked_taker", peg_lp: "peg_lp" };
const parts = [];
for (const [label, key] of Object.entries(want)) {
  const s = secrets[key];
  if (typeof s === "string" && s.startsWith("S")) {
    parts.push(`${label}=${s}`);
    console.log(`dev account ${label}: ${Keypair.fromSecret(s).publicKey()}`);
  }
}
const out = [
  "# generated by e2e/setup-env.mjs: DEV signer with throwaway testnet keys. Never commit.",
  "NEXT_PUBLIC_DEV_SIGNER=1",
  `NEXT_PUBLIC_DEV_SECRET=${parts.join(",")}`,
  "",
].join("\n");
fs.writeFileSync(path.resolve(here, "..", ".env.local"), out, { mode: 0o600 });
console.log("wrote web/.env.local");
